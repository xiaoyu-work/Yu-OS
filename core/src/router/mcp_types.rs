use std::{collections::BTreeSet, fmt::Write, fs::File, io::Read};

use crate::caps::manifest::{Arg, ArgKind, Manifest, McpTool};

pub(super) fn generate(args: &[String]) -> Result<String, String> {
    let [path, flag, language] = args else {
        return Err("usage: yu app tool types <app.json> --lang ts|rust".into());
    };
    if flag != "--lang" || !matches!(language.as_str(), "ts" | "rust") {
        return Err("usage: yu app tool types <app.json> --lang ts|rust".into());
    }
    let limit = yuos_sdk::mcp::MAX_MANIFEST_BYTES;
    let mut body = String::new();
    File::open(path)
        .and_then(|file| file.take((limit + 1) as u64).read_to_string(&mut body))
        .map_err(|error| format!("cannot read App manifest: {error}"))?;
    if body.len() > limit {
        return Err("App manifest exceeds the MCP manifest limit".into());
    }
    let manifest = Manifest::from_json(&body).map_err(|error| error.to_string())?;
    let mcp = manifest.mcp.ok_or("App has no MCP tools")?;
    let mut out =
        String::from("// Generated by `yu app tool types`; regenerate when app.json changes.\n");
    let ts = language == "ts";
    if ts {
        let has_number = mcp
            .tools
            .iter()
            .flat_map(|tool| &tool.args)
            .any(|arg| arg.kind == ArgKind::Number);
        out.push_str("import type { mcp } from \"@yuos/sdk\";\n");
        if has_number {
            out.push_str("import { WireDecimal } from \"@yuos/sdk\";\n");
        }
    }
    let mut modules = BTreeSet::new();
    let prefix = format!("{}.", manifest.id);
    for tool in &mcp.tools {
        let name = ident(tool.name.strip_prefix(&prefix).unwrap_or(&tool.name));
        if !modules.insert(name.clone()) {
            return Err(format!("MCP tools collide on the generated name `{name}`"));
        }
        if ts {
            emit_ts(&mut out, &name, tool);
        } else {
            emit_rust(&mut out, &name, tool)?;
        }
    }
    Ok(out)
}

fn ident(raw: &str) -> String {
    let mut ident: String = raw
        .chars()
        .map(|ch| if ch.is_ascii_alphanumeric() { ch } else { '_' })
        .collect();
    if ident
        .as_bytes()
        .first()
        .is_none_or(|ch| !ch.is_ascii_alphabetic())
    {
        ident.insert_str(0, "arg_");
    }
    ident
}

fn rust_ident(name: &str) -> String {
    if matches!(name, "crate" | "self" | "Self" | "super") {
        format!("arg_{name}")
    } else {
        format!("r#{name}")
    }
}

fn optional(arg: &Arg) -> bool {
    !arg.required && arg.default.is_none()
}

fn emit_ts(out: &mut String, name: &str, tool: &McpTool) {
    let args = format!("{name}_Args");
    if tool.args.is_empty() {
        let _ = writeln!(
            out,
            "\nexport type {args} = Readonly<Record<string, never>>;"
        );
    } else {
        let _ = writeln!(out, "\nexport type {args} = {{");
        for arg in &tool.args {
            let key = serde_json::json!(arg.name);
            let ty = match arg.kind {
                ArgKind::Integer => "number | bigint",
                ArgKind::Number => "number | bigint | WireDecimal",
                ArgKind::Bool => "boolean",
                _ => "string",
            };
            let ty = if arg.repeatable {
                format!("ReadonlyArray<{ty}>")
            } else {
                ty.into()
            };
            let optional = if optional(arg) { "?" } else { "" };
            let _ = writeln!(out, "  readonly {key}{optional}: {ty};");
        }
        out.push_str("};\n");
    }
    let _ = writeln!(out, "export function bind_{name}(app: mcp.App, handler: (args: {args}, context: mcp.CallContext) => ReturnType<mcp.ToolHandler>): void {{");
    let keys: Vec<&str> = tool.args.iter().map(|arg| arg.name.as_str()).collect();
    let _ = writeln!(
        out,
        "  const keys: readonly string[] = {};",
        serde_json::json!(keys)
    );
    let _ = writeln!(
        out,
        "  const matches = (args: Readonly<Record<string, unknown>>): args is {args} =>"
    );
    out.push_str("    Object.keys(args).every(key => keys.includes(key))");
    for arg in &tool.args {
        let value = format!("args[{}]", serde_json::json!(arg.name));
        let check = |value: &str| {
            match arg.kind {
            ArgKind::Integer => format!("(typeof {value} === \"bigint\" || (typeof {value} === \"number\" && Number.isSafeInteger({value})))"),
            ArgKind::Number => format!("(typeof {value} === \"number\" || typeof {value} === \"bigint\" || {value} instanceof WireDecimal)"),
            ArgKind::Bool => format!("typeof {value} === \"boolean\""),
            _ => format!("typeof {value} === \"string\""),
        }
        };
        let predicate = if arg.repeatable {
            format!(
                "(Array.isArray({value}) && {value}.every((item: unknown) => {}))",
                check("item")
            )
        } else {
            check(&value)
        };
        if optional(arg) {
            let _ = write!(out, " &&\n    ({value} === undefined || {predicate})");
        } else {
            let _ = write!(out, " &&\n    ({predicate})");
        }
    }
    let _ = writeln!(
        out,
        ";\n  app.tool({}, (args, context) => {{",
        serde_json::json!(tool.name)
    );
    out.push_str("    if (!matches(args)) throw new Error(\"tool arguments do not match the generated binding\");\n");
    out.push_str("    return handler(args, context);\n  });\n}\n");
}

fn emit_rust(out: &mut String, name: &str, tool: &McpTool) -> Result<(), String> {
    let name = rust_ident(name);
    let _ = writeln!(out, "\npub mod {name} {{");
    out.push_str("    use yuos_sdk::mcp::{App, AppError, CallContext, ToolResult};\n\n");
    out.push_str("    #[derive(Debug, ::serde::Deserialize)]\n    #[serde(deny_unknown_fields)]\n    pub struct Args {\n");
    let mut fields = BTreeSet::new();
    for arg in &tool.args {
        let field = rust_ident(&ident(&arg.name));
        if !fields.insert(field.clone()) {
            return Err(format!(
                "MCP arguments for `{}` collide on generated field `{field}`",
                tool.name
            ));
        }
        let ty = match arg.kind {
            ArgKind::Integer | ArgKind::Number => "::serde_json::Number",
            ArgKind::Bool => "bool",
            _ => "String",
        };
        let ty = if arg.repeatable {
            format!("Vec<{ty}>")
        } else {
            ty.into()
        };
        let ty = if optional(arg) {
            format!("Option<{ty}>")
        } else {
            ty
        };
        let _ = writeln!(
            out,
            "        #[serde(rename = {})]\n        pub {field}: {ty},",
            serde_json::json!(arg.name)
        );
    }
    out.push_str(
        "    }\n\n    pub fn bind<H, R>(app: &mut App, handler: H) -> Result<(), AppError>\n",
    );
    out.push_str("    where\n        H: Fn(Args, CallContext) -> R + Send + Sync + 'static,\n");
    out.push_str(
        "        R: ::std::future::Future<Output = ToolResult> + Send + 'static,\n    {\n",
    );
    let _ = writeln!(
        out,
        "        app.bind_typed({}, handler)\n    }}\n}}",
        serde_json::json!(tool.name)
    );
    Ok(())
}
